/**
 * Returns static sample members purely for the landing page illustration map.
 * Guaranteed to return full, region-authentic member profiles with complete phone numbers,
 * real coordinates, and verified business bios for Chennai, Bengaluru, and Mumbai.
 */
export function getDemoIllustrationMembers(cityOrAccessKey?: string): Member[] {
  const key = (cityOrAccessKey || '').toLowerCase()
  let presetKey: string | undefined

  if (key.includes('blr') || key.includes('bengaluru') || key.includes('bangalore') || key.includes('3e71d80b')) {
    presetKey = 'bengaluru'
  } else if (key.includes('mumbai') || key.includes('bombay') || key.includes('apex') || key.includes('80d4f17a')) {
    presetKey = 'mumbai'
  } else {
    presetKey = 'chennai'
  }

  const preset = CITY_DEMO_PRESETS[presetKey] || CITY_DEMO_PRESETS.chennai

  // Return the rich, region-native members
  return preset.featuredMembers.map((m) => ({
    ...m,
    chapterId: preset.chapterId,
    chapterAccessKey: preset.accessKey,
    chapter: preset.chapterName,
    isVisible: true,
    membershipStatus: 'RENEWED' as const,
  }))
}

/**
 * Retrieves members strictly belonging to a specific chapter.
 * Automatically seeds default chapters with rich regional rosters if empty or outdated.
 */
export function getChapterMembers(chapterId: string): Member[] {
  if (typeof window === 'undefined') return []

  const defaultSeeds: Record<string, string> = {
    'chap-titans': 'chennai',
    'chap-dynamic': 'chennai',
    'chap-royals': 'chennai',
    'chap-blr-central': 'bengaluru',
    'chap-mumbai-apex': 'mumbai',
  }

  // Check persistent storage for this chapter
  try {
    const raw = localStorage.getItem(STORAGE_PREFIX + chapterId)
    if (raw) {
      const parsed: Member[] = JSON.parse(raw)
      // If valid array with full roster (>= 4 members), use it
      if (Array.isArray(parsed) && parsed.length >= 4) {
        return parsed.map((m) => ({
          ...m,
          isVisible: m.isVisible !== false,
          membershipStatus: m.membershipStatus || (m.isVisible === false ? 'NOT_RENEWED' : 'RENEWED'),
        }))
      }
    }
  } catch (err) {
    console.error('Failed reading chapter members:', err)
  }

  // If no saved members or old sparse seed, seed them cleanly
  if (defaultSeeds[chapterId]) {
    const seeded = getDemoIllustrationMembers(defaultSeeds[chapterId]).map((m) => ({
      ...m,
      chapterId,
      isVisible: true,
      membershipStatus: 'RENEWED' as const,
    }))
    saveChapterMembers(chapterId, seeded)
    return seeded
  }

  return []
}

/**
 * Saves members strictly for a specific chapter.
 */
export function saveChapterMembers(chapterId: string, members: Member[]): void {
  if (typeof window === 'undefined') return
  try {
    localStorage.setItem(STORAGE_PREFIX + chapterId, JSON.stringify(members))
  } catch (err) {
    console.error('Failed saving chapter members:', err)
  }
}

/**
 * Toggles a member's renewal/visibility status (Show/Hide on public map).
 * If not renewed, member is hidden from the public chapter map.
 */
export function toggleMemberRenewalStatus(
  chapterId: string,
  memberId: string
): { updatedMembers: Member[]; updatedMember: Member | null } {
  const current = getChapterMembers(chapterId)
  let updatedMember: Member | null = null

  const updatedMembers = current.map((m) => {
    if (m.id === memberId) {
      const willBeVisible = m.isVisible === false
      const updated: Member = {
        ...m,
        isVisible: willBeVisible,
        membershipStatus: willBeVisible ? 'RENEWED' : 'NOT_RENEWED',
      }
      updatedMember = updated
      return updated
    }
    return m
  })

  saveChapterMembers(chapterId, updatedMembers)
  return { updatedMembers, updatedMember }
}
